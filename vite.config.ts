import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import path from 'path';
import {defineConfig, loadEnv, type Plugin} from 'vite';

/**
 * Emits /firebase-messaging-sw.js from the build environment so that each
 * deployment ships the matching Firebase Cloud Messaging service worker.
 *  - `VITE_FIREBASE_USE_PROD=true`  -> production FCM configuration
 *  - `VITE_FIREBASE_*` preview set  -> preview FCM configuration
 *  - missing                        -> SW registers but does nothing
 */
const firebaseMessagingSwPlugin = (): Plugin => ({
  name: 'firebase-messaging-sw',
  apply: 'build',
  generateBundle() {
    const env = loadEnv(process.env.NODE_ENV ?? 'production', process.cwd(), '');
    const useProd = env.VITE_FIREBASE_USE_PROD === 'true';
    const cfg = useProd
      ? {
          apiKey: 'AIzaSyBv_Cf6i4RvL2pikdVhGb8cHUDKYpjjSRA',
          authDomain: 'uselalaoapp.firebaseapp.com',
          projectId: 'uselalaoapp',
          storageBucket: 'uselalaoapp.appspot.com',
          messagingSenderId: '853680775586',
          appId: '1:853680775586:web:1d3beaf2dd0c8dec35d2fb',
        }
      : {
          apiKey: env.VITE_FIREBASE_API_KEY ?? '',
          authDomain: env.VITE_FIREBASE_AUTH_DOMAIN ?? '',
          projectId: env.VITE_FIREBASE_PROJECT_ID ?? '',
          storageBucket: env.VITE_FIREBASE_STORAGE_BUCKET ?? '',
          messagingSenderId: env.VITE_FIREBASE_MESSAGING_SENDER_ID ?? '',
          appId: env.VITE_FIREBASE_APP_ID ?? '',
        };
    const complete = Boolean(
      cfg.apiKey && cfg.authDomain && cfg.projectId && cfg.storageBucket && cfg.messagingSenderId && cfg.appId,
    );

    const source = complete
      ? `// Firebase Cloud Messaging service worker (generated by vite build)
importScripts("https://www.gstatic.com/firebasejs/10.12.0/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/10.12.0/firebase-messaging-compat.js");

firebase.initializeApp(${JSON.stringify(cfg)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title ?? payload.data?.title ?? "Lalao";
  const body = payload.notification?.body ?? payload.data?.body ?? "You have a new notification";
  const url = payload.data?.url ?? payload.fcmOptions?.link ?? "/";
  const icon = payload.notification?.icon ?? payload.data?.icon ?? "/mascot.png";

  self.registration.showNotification(title, {
    body,
    icon,
    badge: "/mascot.png",
    data: { url },
    vibrate: [100, 50, 100],
    tag: "lalao-notification",
    renotify: true,
  });
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = event.notification.data?.url ?? "/";
  event.waitUntil(
    clients
      .matchAll({ type: "window", includeUncontrolled: true })
      .then((clientList) => {
        for (const client of clientList) {
          if (client.url.includes(self.location.origin) && "focus" in client) {
            client.postMessage({ type: "NAVIGATE", url, data: event.notification.data });
            return client.focus();
          }
        }
        if (clients.openWindow) return clients.openWindow(url);
      })
  );
});
`
      : `// Firebase Cloud Messaging service worker (generated by vite build)
// Firebase is not configured for this build/deployment. FCM is disabled;
// this service worker registers but never initializes Firebase or shows notifications.
console.info("[fcm-sw] Firebase not configured for this deployment; push disabled.");
`;

    this.emitFile({
      type: 'asset',
      fileName: 'firebase-messaging-sw.js',
      source,
    });
  },
});

export default defineConfig(() => {
  return {
    plugins: [react(), tailwindcss(), firebaseMessagingSwPlugin()],
    resolve: {
      alias: {
        '@': path.resolve(__dirname, '.'),
        'react': path.resolve(__dirname, 'node_modules/react'),
        'react-dom': path.resolve(__dirname, 'node_modules/react-dom'),
      },
      dedupe: ['react', 'react-dom'],
    },
    optimizeDeps: {
      include: ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime', 'react-router-dom', 'convex/react'],
    },
    build: {
      chunkSizeWarningLimit: 1000,
      rollupOptions: {
        output: {
          manualChunks(id) {
            if (id.includes('node_modules')) {
              if (id.includes('@mux')) return 'vendor-mux';
              if (id.includes('agora-rtc-sdk-ng') || id.includes('agora-token')) return 'vendor-agora';
              if (id.includes('firebase')) return 'vendor-firebase';
              if (id.includes('@google/genai')) return 'vendor-genai';
              if (id.includes('lucide-react')) return 'vendor-lucide';
              if (id.includes('motion')) return 'vendor-motion';
              if (id.includes('convex')) return 'vendor-convex';
              if (id.includes('react') || id.includes('react-dom') || id.includes('react-router-dom')) {
                return 'vendor-react';
              }
            }
          },
        },
      },
    },
    server: {
      // HMR is disabled in AI Studio via DISABLE_HMR env var.
      // Do not modify—file watching is disabled to prevent flickering during agent edits.
      hmr: process.env.DISABLE_HMR !== 'true',
      // Disable file watching when DISABLE_HMR is true to save CPU during agent edits.
      watch: process.env.DISABLE_HMR === 'true' ? null : {
        ignored: ['**/.kilo/**', '**/.git/**', '**/dist/**'],
      },
    },
  };
});
